import pandas as pd


def get_data(data_source: str) -> pd.DataFrame:
    """
    Fetch data from various sources based on the data_source parameter.

    Args:
        data_source: String identifier for the data source

    Returns:
        pandas.DataFrame: The requested data

    Raises:
        ValueError: If data_source is not recognized
        FileNotFoundError: If required CSV file is not found
    """
    # TODO: Replace with actual API calls to BlockAnalitica or other data sources
    # For now, using existing CSV files as data sources

    data_mapping: dict[str, str] = {
        "spark_v1ethereummarket": "assets.csv",
        "spark_v1gnosismarket": "assets.csv",  # Using same file, will filter by network
        "spark_v1ethereumemodecategoryaddedevent": "assets.csv",
        "spark_v1ethereumsdaimarket": "sdai_wallets.csv",
        "spark_v1potdsr": "pot_dsr.csv",
        "spark_v1ethereumcurrentmarketstate": "assets.csv"
    }

    if data_source not in data_mapping:
        raise ValueError(f"Unknown data source: {data_source}")

    csv_file = data_mapping[data_source]

    try:
        df = pd.read_csv(csv_file)

        # Apply filtering based on data source
        if data_source == "spark_v1gnosismarket":
            # Filter for gnosis network data if available
            if "network" in df.columns:
                df = df[df["network"] == "gnosis"].copy()
        elif data_source == "spark_v1ethereummarket":
            # Filter for ethereum network data if available
            if "network" in df.columns:
                df = df[df["network"] == "ethereum"].copy()

        return df
    except FileNotFoundError as e:
        raise FileNotFoundError(f"Required data file not found: {csv_file}") from e
    except pd.errors.EmptyDataError as e:
        raise ValueError(f"Data file is empty: {csv_file}") from e


# sparklend
df_market_ethereum = get_data("spark_v1ethereummarket")
df_market_gnosis = get_data("spark_v1gnosismarket")
df_market_ethereum["network"] = "ethereum"
df_market_gnosis["network"] = "gnosis"
db_markets = pd.concat([df_market_ethereum, df_market_gnosis], ignore_index=True)

emode_categories = get_data("spark_v1ethereumemodecategoryaddedevent")
db_markets_merged = pd.merge(
    db_markets,
    emode_categories[
        ["category", "name", "ltv", "liquidation_threshold", "liquidation_bonus"]
    ],
    left_on="emode_category",
    right_on="category",
    how="left",
    suffixes=(None, "_emode"),
)
db_markets_merged.to_csv("assets.csv", index=False)

# sdai
sdai_wallets = get_data("spark_v1ethereumsdaimarket")
sdai_wallets.to_csv("sdai_wallets.csv", index=False)

pot_dsr = get_data("spark_v1potdsr")
pot_dsr.to_csv("pot_dsr.csv", index=False)


